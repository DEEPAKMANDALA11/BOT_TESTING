        "            self.parts.append(block)\n",
        "            self.left -= len(block)\n",
        "    def text(self):\n",
        "        return \"\".join(self.parts) + (\"\\n[context truncated to fit the size limit]\" if self.truncated else \"\")\n",
        "\n",
        "def stmt_blocks(idx, pairs, budget, label, cap):\n",
        "    for s, hs in pairs:\n",
