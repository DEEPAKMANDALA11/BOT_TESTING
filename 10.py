        "# ---------------------------------------------------------------\n",
        "# 9) Post-checks on the model's answer\n",
        "# ---------------------------------------------------------------\n",
        "FILE_RX = re.compile(r\"`([\\w./\\-]+\\.[A-Za-z0-9]{1,6})`\")\n",
        "TICK_RX = re.compile(r\"`([^`\\n]{3,80})`\")\n",
