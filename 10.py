        "              \"create\", \"drop\", \"truncate\", \"alter\", \"table\", \"view\", \"set\", \"into\", \"values\", \"like\", \"and\",\n",
        "              \"or\", \"not\", \"in\", \"is\", \"as\", \"on\", \"all\", \"date\", \"timestamp\", \"varchar\", \"integer\", \"decimal\",\n",
